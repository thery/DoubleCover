  done;
  exit 0

(* ---- the level, translated from the Rocq LITERALLY ---------------------- *)

(* The mode above is the level written the way one writes OCaml.  This one is
   RowFold.v turned into OCaml line by line: the same ifold walking a count
   with a closure, the same flat tables read by the same arithmetic, the same
   packed source word taken apart by shifting.  Nothing is hoisted that the
   Rocq does not hoist.  What it costs is what the PROGRAM costs; whatever
   Rocq costs beyond it is the evaluator. *)

(* THE COUNT IS A UNARY NAT, as it is in the Rocq: `ifold ngroupn' walks
   twenty thousand constructors, one match a word, and ngroupn itself is
   to_nat of an int63.  An int counter here would not be the same program. *)
type unat = O | S of unat

let rec unat_of n = if n = 0 then O else S (unat_of (n - 1))

(* THE TABLES ARE PERSISTENT ARRAYS TOO.  In the Rocq every one of these is a
   PArray, so a read is a deref, a match and a bounds check; a plain OCaml
   array here is one indexed load, and there are six of them a word in the
   inner loop.  That difference alone flattered this side fourfold. *)
let pof (a : int array) : int P.t =
  let t = ref (P.make (Array.length a) 0) in
  Array.iteri (fun i v -> t := P.set !t i v) a; !t

let lfsrc = pof (Array.init (nrep * nh) (fun i ->
  let r = i / nh and k = i mod nh in
  let q = mpginv.(reps.(r)).(k) in
  let p = repof.(q) in
  (repix.(p) * nsym + sinv.(symof.(q))) * 2 + pgpar.(p)))
let lfsgr = pof (Array.init (nsym * 2 * ngroup) (fun i ->
  sgr.(i / (2 * ngroup)).(i / ngroup mod 2).(i mod ngroup)))
let lfslo = pof (Array.init (nsym * 4096) (fun i -> slo.(i / 4096).(i mod 4096)))
let lfshi = pof (Array.init (nsym * 4096) (fun i -> shi.(i / 4096).(i mod 4096)))
let lmgr = pof (Array.init (ngroup * nh) (fun i -> mgroup.(i / nh).(i mod nh)))
let lmlo = pof (Array.init (nh * 4096) (fun i -> mlo.(i / 4096).(i mod 4096)))
let lmhi = pof (Array.init (nh * 4096) (fun i -> mhi.(i / 4096).(i mod 4096)))
let lmsw = pof (Array.init nh (fun k -> mswap.(k)))

(* ifold, as RowMap.v has it: a nat, a running int, a closure a step *)
let rec ifold (n : unat) x f a =
  match n with O -> a | S n1 -> ifold n1 (x + 1) f (f x a)

let ngroupn = unat_of ngroup
let nhn = unat_of nh
let nrepn = unat_of nrep
let un18 = unat_of 18

let lo12 = 4095
let nhi = nh

let fpar w = w land 1
let fren w = (w lsr 1) land 15
let fkpt w = w lsr 5

let pchk r = r lsr 6
let poff r = (r land 63) * ngroup

let lflevmv (src : pmap) r k doff (a : int P.t) : int P.t =
  let w = P.get lfsrc (r * nhi + k) in
  let u = fren w in
  let pc = fpar w in
  let p = fkpt w in
  let sa = P.get src (pchk p) in
  let soff = poff p in
  let glo = (u * 2 + pc) * ngroup in
  let ghi = (u * 2 + (1 - pc)) * ngroup in
  let ub = u lsl 12 in
  let kb = k lsl 12 in
  let sw = P.get lmsw k = 0 in
  ifold ngroupn 0
    (fun g b ->
       let v = P.get sa (soff + g) in
       if v = 0 then b
       else
         let lo = v land lo12 in
         let hi = (v lsr 12) land lo12 in
         let b1 =
           if lo = 0 then b
           else
             let l = P.get lmlo (kb + P.get lfslo (ub + lo)) in
             let j = doff + P.get lmgr (P.get lfsgr (glo + g) * nhi + k) in
             P.set b j (P.get b j lor (if sw then l else l lsl 12)) in
         if hi = 0 then b1
         else
           let h = P.get lmhi (kb + P.get lfshi (ub + hi)) in
           let j = doff + P.get lmgr (P.get lfsgr (ghi + g) * nhi + k) in
           P.set b1 j (P.get b1 j lor (if sw then h lsl 12 else h)))
    a

let lflevpg (src : pmap) r (d : pmap) : pmap =
  let c = pchk r in
  let doff = poff r in
  let sa = P.get src c in
  let a0 = P.get d c in
  let a1 = ifold ngroupn 0
      (fun g b -> let j = doff + g in P.set b j (P.get sa j)) a0 in
  let a2 = ifold nhn 0 (fun k b -> lflevmv src r k doff b) a1 in
  P.set d c a2

let lflevel (src : pmap) (dst : pmap) : pmap =
  ifold nrepn 0 (fun r d -> lflevpg src r d) dst

(* THE LEAKING SHAPE, LITERALLY.  Before the fix the Rocq level made a fresh
   map every time and the run started from a GLOBAL empty map, which nothing
   can collect.  This is that, in OCaml: the same literal level, a new map a
   level, and a global root held for the whole run.  If the heap grows here
   too then the shape leaks and the evaluator is not to blame; if it does not,
   the leak is native_compute's. *)

let lglobal : pmap = pmkempty ()

let lflevel_fresh (src : pmap) : pmap =
  ifold nrepn 0 (fun r d -> lflevpg src r d) (pmkempty ())

let lleak n =
  Printf.printf "the leaking shape: a fresh map a level, a global root held\n%!";
  let s = solved () in
  let pg = rank s.cp 0 8 in
  let sy = syms.(symof.(pg)) in
  let b12 = Array.make 12 0 in
  for j = 0 to 11 do b12.(sy.se.(j)) <- sy.se.(s.ep.(j)) done;
  let r = repix.(repof.(pg)) in
  let gr = e8num.(rank b12 0 8) lsr 1 and bt = e4bit.(rank b12 8 4) in
  (* the seed is written INTO the global, as fseed was *)
  let a = P.get lglobal (pchk r) in
  let j = poff r + gr in
  let a = P.set a j (P.get a j lor (1 lsl (bt mod 12))) in
  let cur = ref (P.set lglobal (pchk r) a) in
  Printf.printf "level  0 : %d\n%!" (pcount !cur);
  for d = 1 to n do
    let t0 = Unix.gettimeofday () in
    cur := lflevel_fresh !cur;
    let t1 = Unix.gettimeofday () in
    Printf.printf "level %2d : %d (%.1f s, heap %.2f GB)\n%!"
      d (pcount !cur) (t1 -. t0)
      (float_of_int (Gc.stat ()).Gc.heap_words *. 8.0 /. 1e9)
  done;
  (* the global is still held here, which is the whole point *)
  Printf.printf "the global is still alive: %d\n%!" (pcount lglobal);
  exit 0

