(* ---- the fold, checked ------------------------------------------------- *)

(* The tables above are built from the renamings; these are the facts they
   have to have, and each is run rather than argued. *)
let fcheck fail =
  (* a renaming sends a move of H to a move of H *)
  for s = 0 to nsym - 1 do
    Array.iter (fun m ->
      if not (Array.exists (fun x -> x = symmv.(s).(m)) hmoves) then
        fail "a renaming takes a move of H outside H") hmoves
  done;
  (* and it leaves the superflip alone, which is what lets the row be
     folded at all *)
  let sf = { cp = Array.init 8 (fun i -> i); co = Array.make 8 0;
             ep = Array.init 12 (fun i -> i); eo = Array.make 12 1 } in
  for s = 0 to nsym - 1 do
    let c = conj syms.(s) sf in
    if not (same c.cp sf.cp 8 && same c.co sf.co 8
            && same c.ep sf.ep 12 && same c.eo sf.eo 12) then
      fail "a renaming moves the superflip"
  done;
  (* a renaming is an automorphism: it may be played before or after a
     product, and the answer is the same *)
  let seed = ref 999331 in
  let rnd n = seed := (!seed * 1103515245 + 12345) land 0x3FFFFFFF;
    !seed mod n in
  for _ = 1 to 200 do
    let a = ref (solved ()) and b = ref (solved ()) in
    for _ = 1 to 8 do
      a := mult !a moves.(rnd 18); b := mult !b moves.(rnd 18) done;
    for s = 0 to nsym - 1 do
      let x = conj syms.(s) (mult !a !b) in
      let y = mult (conj syms.(s) !a) (conj syms.(s) !b) in
      if not (same x.cp y.cp 8 && same x.co y.co 8
              && same x.ep y.ep 12 && same x.eo y.eo 12) then
        fail "a renaming is not an automorphism"
    done
  done;
  (* the pages fall into orbits, and every page is in exactly one *)
  let tot = ref 0 in
  for r = 0 to nrep - 1 do tot := !tot + orbsz.(r) done;
  if !tot <> npage then fail "the page orbits do not cover the pages";
  for p = 0 to npage - 1 do
    if repof.(p) < 0 || repix.(repof.(p)) < 0 then fail "a page has no orbit";
    if spg.(symof.(p)).(p) <> repof.(p) then
      fail "the renaming of a page does not fold it"
  done;
  (* a renaming keeps a parity, and so keeps a half where it was *)
  for s = 0 to nsym - 1 do
    for pty = 0 to 1 do
      if e8num.(e8inv.(2 * sgr.(s).(pty).(0) + pty)) land 1 <> pty then
        fail "a renaming changes an outer parity"
    done;
    for b = 0 to 11 do
      if sbt.(s).(b) >= 12 || sbt.(s).(12 + b) < 12 then
        fail "a renaming changes a middle half"
    done
  done;
  (* THE CHECK THAT MATTERS: where the tables send a place is where the
     renaming sends the member.  Take a member of H and a renaming, and
     compare the place of the renamed member with the place the tables
     give. *)
  let c = ref (solved ()) in
  for _ = 1 to 20000 do
    c := mult !c moves.(hmoves.(rnd nh));
    let p = !c in
    let (pg, gr, bt) = place p in
    let pty = e8num.(rank p.ep 0 8) land 1 in
    for s = 0 to nsym - 1 do
      let (pg', gr', bt') = place (conj syms.(s) p) in
      if spg.(s).(pg) <> pg' then fail "the page fold table is wrong";
      if sgr.(s).(pty).(gr) <> gr' then fail "the group fold table is wrong";
      if sbt.(s).(bt) <> bt' then fail "the bit fold table is wrong"
    done
  done;
  Printf.printf
    "the fold: %d renamings, %d pages of %d kept, map %.2f GB against %.2f\n"
    nsym nrep npage
    (float_of_int (4 * 2 * fsize) /. 1e9)
    (float_of_int (4 * 2 * mapsize) /. 1e9)

let check () =
  let bad = ref 0 in
  let fail s = incr bad; print_string ("FAILED: " ^ s ^ "\n") in

  (* the numbering of the outer edges, and of the middle four *)
  let seen = Array.make fact8 0 in
  Array.iter (fun x -> seen.(x) <- seen.(x) + 1) e8num;
  if Array.exists (fun x -> x <> 1) seen then fail "the outer numbers repeat";
  for r = 0 to fact8 - 1 do
    if e8num.(r) land 1 <> parity (unrank r 8) 0 8 then
      fail "an outer number does not carry its parity"
  done;
  let seen = Array.make fact4 0 in
  Array.iter (fun x -> seen.(x) <- seen.(x) + 1) e4bit;
  if Array.exists (fun x -> x <> 1) seen then fail "the middle bits repeat";
  for r = 0 to fact4 - 1 do
    if (e4bit.(r) >= 12) <> (parity (unrank r 4) 0 4 = 1) then
      fail "a middle bit is in the wrong half"
  done;

  (* THE THREE AXES ARE THREE DIFFERENT NOTIONS OF H, which is the whole
     reason to have them: the ten moves of one axis are not the ten moves of
     another, so a position phase one cannot fit inside twenty on one is a
     different problem on the next.  That every move is renamed to a move is
     checked at startup, on all eighteen and all three. *)
  for i = 1 to Array.length axes - 1 do
    let kept = Array.for_all
        (fun m -> Array.exists (fun x -> x = axmv i m) hmoves) hmoves in
    if kept then fail (Printf.sprintf "axis %d keeps H where it was" i)
  done;

  (* AN AXIS RENAMES A WORD, and this is the direction the leftover solver
     depends on: a word that solves a position solves the position turned by
     an axis, once each of its moves is renamed.  Twenty random words, all
     three axes, both ways round. *)
  let iax = [| 0; 2; 1 |] in                 (* the axis that undoes an axis *)
  let isolved c =
    let ok = ref true in
    for i = 0 to 7 do
      if c.cp.(i) <> i || c.co.(i) <> 0 then ok := false done;
    for i = 0 to 11 do
      if c.ep.(i) <> i || c.eo.(i) <> 0 then ok := false done;
    !ok in
  let play q w = List.fold_left (fun c m -> mult c moves.(m)) q w in
  let seed = ref 12345 in
  let rnd n = seed := (!seed * 1103515245 + 12345) land 0x3FFFFFFF;
    !seed mod n in
  for _ = 1 to 20 do
    let u = List.init 12 (fun _ -> rnd 18) in
    let q = play (solved ()) u in
    let sol = List.rev_map (fun m -> 3 * (m / 3) + (2 - m mod 3)) u in
    for i = 0 to Array.length axes - 1 do
      let a = axes.(i) in
      let qa = mult (mult (inv a) q) a in
      let w = List.map (axmv iax.(i)) sol in
      if not (isolved (play qa w)) then
        fail (Printf.sprintf "axis %d does not carry a word over" i);
      if not (isolved (play q (List.map (axmv i) w))) then
        fail (Printf.sprintf "axis %d does not bring a word back" i)
    done
  done;

  (* the ten moves keep a position in H, and no other move does *)
  for m = 0 to 17 do
    let there = Array.exists (fun x -> x = m) hmoves in
    if in_h moves.(m) <> there then fail (Printf.sprintf "move %d in H" m)
  done;

  (* F2 is the exchange of the two halves and nothing else *)
  let kf2 = ref (-1) in
  Array.iteri (fun k m -> if m = f2 then kf2 := k) hmoves;
  let k = !kf2 in
  if mswap.(k) <> 1 then fail "F2 does not change half";
  for i = 0 to 4095 do
    if mlo.(k).(i) <> i || mhi.(k).(i) <> i then fail "F2 moves a bit"
  done;

  (* THE CHECK THAT MATTERS: where the prepass sends a bit is where the move
     sends the position.  Take a member of H, take a move of H, and compare
     the place of the product with the place the tables give. *)
  Random.self_init ();
  let places = Hashtbl.create 100003 in
  let c = ref (solved ()) in
  for _ = 1 to 200000 do
    c := mult !c moves.(hmoves.(Random.int nh));
    let p = !c in
    if not (in_h p) then fail "a word of H left H";
    let (pg, gr, bt) = place p in
    if pg < 0 || pg >= npage || gr < 0 || gr >= ngroup
       || bt < 0 || bt >= fact4 then fail "the place is out of range";
    let key = (pg * ngroup + gr) * fact4 + bt in
    let sg = (Array.to_list p.cp, Array.to_list p.ep) in
    (match Hashtbl.find_opt places key with
     | Some s when s <> sg -> fail "two members share a place"
     | _ -> Hashtbl.replace places key sg);
    for k = 0 to nh - 1 do
      let q = mult p moves.(hmoves.(k)) in
      let (pg', gr', bt') = place q in
      if mpage.(pg).(k) <> pg' then fail "the page table is wrong";
      if mgroup.(gr).(k) <> gr' then fail "the group table is wrong";
      let half = bt / 12 and j = bt mod 12 in
      let want = if half = 0 then mlo.(k).(1 lsl j) else mhi.(k).(1 lsl j) in
      let half' = if half = 0 then mswap.(k) else 1 - mswap.(k) in
      if want <> 1 lsl (bt' mod 12) || half' <> bt' / 12 then
        fail "the bit table is wrong"
    done
  done;

  (* reading a place back gives the member that was put there *)
  let c = ref (solved ()) in
  for _ = 1 to 20000 do
    c := mult !c moves.(hmoves.(Random.int nh));
    let p = !c in
    let (pg, gr, bt) = place p in
    let q = unplace pg gr bt in
    if q.cp <> p.cp || q.ep <> p.ep then fail "a place reads back wrong"
  done;

  (* phase two solves a member of H, and the word is checked by playing it *)
  let worst = ref 0 in
  for _ = 1 to 300 do
    c := mult !c moves.(hmoves.(Random.int nh));
    let p = !c in
    match phase2 (h2coord p) 20 with
    | None -> fail "phase two found no word"
    | Some w ->
      if List.length w > !worst then worst := List.length w;
      let q = ref p in
      List.iter (fun m ->
        if not (Array.exists (fun x -> x = m) hmoves) then
          fail "phase two used a move outside H";
        q := mult !q moves.(m)) w;
      for i = 0 to 7 do
        if (!q).cp.(i) <> i then fail "phase two did not solve the corners" done;
      for i = 0 to 11 do
        if (!q).ep.(i) <> i then fail "phase two did not solve the edges" done
  done;
  Printf.printf "phase two solved 300 members of H, longest %d moves\n" !worst;

  (* the move rule counts the canonical sequences, which Canseq.v proves are
     18, 243, 3240, 43254 and 577368 *)
  let opp f = (f + 3) mod 6 in
  let rec count d prev =
    if d = 0 then 1L
    else begin
      let n = ref 0L in
      for m = 0 to 17 do
        let f = m / 3 in
        if prev < 0 || not (f = prev || (f = opp prev && f > prev)) then
          n := Int64.add !n (count (d - 1) f)
      done; !n
    end in
  let want = [| 18L; 243L; 3240L; 43254L; 577368L |] in
  for d = 1 to 5 do
    let got = count d (-1) in
    if got <> want.(d - 1) then
      fail (Printf.sprintf "canonical sequences of %d: %Ld, not %Ld"
              d got want.(d - 1))
  done;

  fcheck fail;

  Printf.printf "row %d members, %d pages of %d groups of 24 bits\n"
    rowsize npage ngroup;
  Printf.printf "%d distinct members of H sampled\n" (Hashtbl.length places);
  if !bad = 0 then print_string "all checks passed\n"
  else Printf.printf "%d checks FAILED\n" !bad;
  exit (if !bad = 0 then 0 else 1)

(* ======================================================================== *)

(* The prepass on its own, from the solved position: level n is every member
   of H that ten moves of H reach in n.  For the first levels the same thing
   is worked out one position at a time, with a table of what has been seen,
   and the two must agree. *)
let hball n =
  Printf.printf "the map is %.2f GB%s\n%!" (mapgb ())
    (if !usefold then Printf.sprintf ", %d pages of %d kept" nrep npage else "");
  alloc ();
  mark_at (solved ()).cp (solved ()).ep;
  swapmaps ();
  let seen = Hashtbl.create 1000003 in
  let front = ref [ solved () ] in
  Hashtbl.replace seen (Array.to_list (solved ()).cp,
                        Array.to_list (solved ()).ep) ();
  Printf.printf "level  0 : %d\n%!" (count ());
  for d = 1 to n do
    let t0 = Unix.gettimeofday () in
    carry (); swapmaps ();
    let got = count () in
    let t1 = Unix.gettimeofday () in
    if d <= 5 then begin
      let nf = ref [] in
      List.iter (fun p ->
        Array.iter (fun m ->
          let q = mult p moves.(m) in
          let key = (Array.to_list q.cp, Array.to_list q.ep) in
          if not (Hashtbl.mem seen key) then begin
            Hashtbl.replace seen key (); nf := q :: !nf
          end) hmoves) !front;
      front := !nf;
      let want = Hashtbl.length seen in
      Printf.printf "level %2d : %d, one at a time %d, %s (%.1f s)\n%!"
        d got want (if got = want then "agree" else "DISAGREE") (t1 -. t0)
    end else
      Printf.printf "level %2d : %d (%.1f s)\n%!" d got (t1 -. t0)
  done;
  exit 0

let () =
  (* `dumptab' writes the twelve tables of one row as Rocq lists, in the
     convention the generated files of this development already use: one
     `Definition foo_data : seq int', eight numbers to a line.  What Rocq
     does with them is CHECK them -- Row.e8ok and Row.e4ok over the layout,
     and the two over the bits -- so nothing here has to be trusted. *)
  if Array.length Sys.argv > 2 && Sys.argv.(1) = "dumptab" then begin
    let which = Sys.argv.(2) in
    let out = Buffer.create (1 lsl 22) in
    let emit name n get =
      Buffer.add_string out
        (Printf.sprintf "Definition %s : seq int := [::\n" name);
      for i = 0 to n - 1 do
        Buffer.add_string out (string_of_int (get i));
        if i = n - 1 then Buffer.add_string out "].\n\n"
        else if i mod 8 = 7 then Buffer.add_string out ";\n"
        else Buffer.add_string out "; "
      done in
    Buffer.add_string out
      "(* GENERATED by ocaml/rubik_row.ml dumptab -- do not edit.               \
       \     *)\n\
       (* The layout and the prepass tables of one row.  Rocq checks them; it \
       does  *)\n\
       (* not build them.                                                     \
        \      *)\n\n\
       From Stdlib Require Import Uint63.\n\
       From mathcomp Require Import all_ssreflect.\n\n\
       Local Open Scope uint63_scope.\n\n";
    (* the layout: rank to number and back, rank to bit and back, the two
       parities *)
    (* THE FOLD.  What the folded level reads: for a page, where it is kept
       and through which renaming; for a kept page and a move, the page it
       gathers from, already folded; and the renaming played on a group and
       on the twelve bits of a half.  A page and its renaming are run
       together into one number, and so are a source and its parity, so that
       the level reads one word where it would otherwise read three. *)
    if which = "fold" then begin
    emit "fnrep_data" 1 (fun _ -> nrep);
    emit "fkeep_data" nrep (fun r -> reps.(r));
    emit "forb_data" nrep (fun r -> orbsz.(r));
    (* a page: its kept page, the renaming that folds it, and its parity *)
    emit "fpg_data" npage
      (fun p -> (repix.(repof.(p)) * nsym + symof.(p)) * 2 + pgpar.(p));
    (* a kept page and a move of H: the kept page it gathers from, the
       renaming to read it through, and that page's parity *)
    emit "fsrc_data" (nrep * nh)
      (fun i ->
         let r = i / nh and k = i mod nh in
         let q = mpginv.(reps.(r)).(k) in
         let p = repof.(q) in
         (repix.(p) * nsym + sinv.(symof.(q))) * 2 + pgpar.(p));
    (* a renaming on a group, told apart by parity, and on the bits *)
    emit "fsgr_data" (nsym * 2 * ngroup)
      (fun i -> sgr.(i / (2 * ngroup)).(i / ngroup mod 2).(i mod ngroup));
    emit "fslo_data" (nsym * 4096) (fun i -> slo.(i / 4096).(i mod 4096));
    emit "fshi_data" (nsym * 4096) (fun i -> shi.(i / 4096).(i mod 4096));
    emit "fsbt_data" (nsym * fact4)
      (fun i -> sbt.(i / fact4).(i mod fact4));
    (* the bits of a half counted, so that the members can be counted: a bit
       of a kept page stands for as many members as its orbit has pages *)
    emit "fpop_data" 4096 (fun i -> popc.(i))
    end else if which = "layout" then begin
    emit "e8num_data" fact8 (fun r -> e8num.(r));
    emit "e8inv_data" fact8 (fun r -> e8inv.(r));
    emit "par8_data" fact8 (fun r -> parity (unrank r 8) 0 8);
    emit "e4bit_data" fact4 (fun r -> e4bit.(r));
    emit "e4of_data" fact4 (fun r -> e4of.(r));
    emit "par4_data" fact4 (fun r -> parity (unrank r 4) 0 4)
    end else begin
    (* the prepass: a page to a page, a group to a group, the bits *)
    emit "mpg_data" (npage * nh) (fun i -> mpage.(i / nh).(i mod nh));
    emit "mgr_data" (ngroup * nh) (fun i -> mgroup.(i / nh).(i mod nh));
    emit "msw_data" nh (fun k -> mswap.(k));
    emit "mlo_data" (nh * 4096) (fun i -> mlo.(i / 4096).(i mod 4096));
    emit "mhi_data" (nh * 4096) (fun i -> mhi.(i / 4096).(i mod 4096));
    (* THE PERMUTATION OF A RANK, which is the one thing Rocq cannot read off
       a smaller table: unranking is a computation and the layout tables are
       written in terms of it.  Eight numbers a corner rank, four a middle
       one. *)
    emit "up8_data" (fact8 * 8)
      (fun i -> (unrank (i / 8) 8).(i mod 8));
    emit "up4_data" (fact4 * 4)
      (fun i -> (unrank (i / 4) 4).(i mod 4));
    (* and where each of the twenty four bits goes, move by move *)
    emit "btmv_data" (fact4 * nh)
      (fun i -> let bt = i / nh and k = i mod nh in
                e4bit.(e4move.(e4of.(bt)).(hmoves.(k))))
    end;
    print_string (Buffer.contents out);
    exit 0
  end;
  if Array.length Sys.argv > 1 && Sys.argv.(1) = "check" then check ();
  if Array.length Sys.argv > 2 && Sys.argv.(1) = "hball" then
    hball (int_of_string Sys.argv.(2));
  if Array.length Sys.argv > 2 && Sys.argv.(1) = "fball" then begin
    usefold := true; hball (int_of_string Sys.argv.(2)) end;
  if Array.length Sys.argv > 2 && Sys.argv.(1) = "pball" then
    pball (int_of_string Sys.argv.(2));
  if Array.length Sys.argv > 2 && Sys.argv.(1) = "lball" then
    lball (int_of_string Sys.argv.(2));
  if Array.length Sys.argv > 2 && Sys.argv.(1) = "lleak" then
    lleak (int_of_string Sys.argv.(2));
  if Array.length Sys.argv > 2 && Sys.argv.(1) = "lsrch" then
    lsrchrun (int_of_string Sys.argv.(2));
  if Array.length Sys.argv > 1 && Sys.argv.(1) = "ptest" then ptest ();
  if Array.length Sys.argv > 2 && Sys.argv.(1) = "lrow" then
    lrow (int_of_string Sys.argv.(2));
  let cap = int_of_string Sys.argv.(1) in
  let maxdepth = int_of_string Sys.argv.(2) in
  let arg = if Array.length Sys.argv > 3 then Sys.argv.(3) else "" in
  let maxsearch =
    if Array.length Sys.argv > 4 then int_of_string Sys.argv.(4)
    else maxdepth in
  let build_only = (arg = "build") in

  let mt_twist = mk_move_table n_twist cube_of_twist twist in
  let mt_flip  = mk_move_table n_flip  cube_of_flip  flip  in
  let mt_slice = mk_move_table n_slice cube_of_slice slice in

  (* the pruning table, shared through the file system *)
  let n_all = n_twist * n_flip * n_slice in
  let path = Printf.sprintf "phase1_cap%d.tbl" cap in
  let fresh = not (Sys.file_exists path) in
  let fd = Unix.openfile path
      (if fresh then [Unix.O_RDWR; Unix.O_CREAT] else [Unix.O_RDONLY]) 0o644 in
  let p_all = Bigarray.array1_of_genarray
      (Unix.map_file fd Bigarray.char Bigarray.c_layout fresh [| n_all |]) in
  Unix.close fd;
  if fresh then begin
    Printf.printf "building phase-1 table (%d states, cap %d)...\n%!" n_all cap;
    let t0 = Unix.gettimeofday () in
    Bigarray.Array1.fill p_all (Char.chr (cap + 1));
    Bigarray.Array1.unsafe_set p_all 0 '\000';
    for cur = 0 to cap - 1 do
      let added = ref 0 in
      for t = 0 to n_twist - 1 do
        let mtt = mt_twist.(t) in
        for f = 0 to n_flip - 1 do
          let mtf = mt_flip.(f) in
          let base = (t * n_flip + f) * n_slice in
          for s = 0 to n_slice - 1 do
            if Char.code (Bigarray.Array1.unsafe_get p_all (base + s)) = cur then begin
              let mts = mt_slice.(s) in
              for m = 0 to 17 do
                let j = (mtt.(m) * n_flip + mtf.(m)) * n_slice + mts.(m) in
                if Char.code (Bigarray.Array1.unsafe_get p_all j) > cur + 1 then begin
                  Bigarray.Array1.unsafe_set p_all j (Char.chr (cur + 1)); incr added end
              done
            end
          done
        done
      done;
      Printf.printf "   depth %d -> %d states (%.0f s)\n%!" (cur + 1) !added
        (Unix.gettimeofday () -. t0)
    done
  end;
  (* THE MASK TABLE.  Sweeping it is fast because of how the index is laid
     out: for a twist and a flip held fixed, the eighteen children of all 495
     slice values sit in eighteen runs of 495 bytes, so the whole sweep works
     out of cache. *)
  let mpath = Printf.sprintf "phase1m%d.tbl" cap in
  let want_mask = (arg = "mask") in
  let has_mask = Sys.file_exists mpath in
  if want_mask && has_mask then begin
    Printf.printf "%s is already there\n%!" mpath; exit 0 end;
  (* Cap 12 is not a soundness matter -- the masks are right at any cap,
     because a capped table is still a lower bound and still moves by at most
     one a turn.  It is that the cap does not change the table's SIZE, so a
     lower one would cost the same 17.7 GB and prune worse. *)
  if want_mask && cap < 12 then begin
    prerr_endline "the cap does not change the size, so build it exact: 12";
    exit 1 end;
  let p_msk =
    if not (want_mask || has_mask) then
      Bigarray.Array1.create Bigarray.int Bigarray.c_layout 0
    else begin
      let fd = Unix.openfile mpath
          (if want_mask then [Unix.O_RDWR; Unix.O_CREAT] else [Unix.O_RDONLY])
          0o644 in
      let a = Bigarray.array1_of_genarray
          (Unix.map_file fd Bigarray.int Bigarray.c_layout want_mask
             [| n_all |]) in
      Unix.close fd; a
    end in
  if want_mask then begin
    Printf.printf "building the mask table (%d words, %.1f GB)...\n%!"
      n_all (float_of_int n_all *. 8.0 /. 1e9);
    let t0 = Unix.gettimeofday () in
    let base = Array.make 18 0 in
    for t = 0 to n_twist - 1 do
      let mtt = mt_twist.(t) in
      for f = 0 to n_flip - 1 do
        let mtf = mt_flip.(f) in
        let here = (t * n_flip + f) * n_slice in
        for m = 0 to 17 do
          base.(m) <- (mtt.(m) * n_flip + mtf.(m)) * n_slice done;
        for s = 0 to n_slice - 1 do
          let mts = mt_slice.(s) in
          let d = Char.code (Bigarray.Array1.unsafe_get p_all (here + s)) in
          let down = ref 0 and flat = ref 0 in
          for m = 0 to 17 do
            let dc = Char.code (Bigarray.Array1.unsafe_get p_all
                                  (Array.unsafe_get base m + mts.(m))) in
            if dc < d then down := !down lor (1 lsl m);
            if dc <= d then flat := !flat lor (1 lsl m)
          done;
          Bigarray.Array1.unsafe_set p_msk (here + s)
            (d lor (!down lsl 5) lor (!flat lsl 23))
        done
      done;
      if t land 255 = 0 then
        Printf.printf "   twist %d of %d (%.0f s)\n%!" t n_twist
          (Unix.gettimeofday () -. t0)
    done;
    Printf.printf "the mask table took %.0f s\n%!"
      (Unix.gettimeofday () -. t0);
    exit 0
  end;
  if build_only then exit 0;

  (* ROWPLACE="pg gr bt" skips the row and attacks that one place, so a
     leftover can be worked on in seconds instead of rerunning the row. *)
  let rowplace =
    match Sys.getenv_opt "ROWPLACE" with
    | Some v when v <> "" ->
      (match List.filter (fun s -> s <> "") (String.split_on_char ' ' v) with
       | [a; b; c] -> Some (int_of_string a, int_of_string b, int_of_string c)
       | _ -> prerr_endline "ROWPLACE wants three numbers"; exit 1)
    | _ -> None in
  let rowsolve = match Sys.getenv_opt "ROWSOLVE" with
    | Some v -> v <> "" | None -> false in
  let repseq = parse_moves arg in
  let rep = ref (solved ()) in
  List.iter (fun m -> rep := mult !rep moves.(m)) repseq;
  let rep = !rep in

  (* ROWFOLD=1 keeps one page of each orbit of the sixteen renamings.  That
     is sound only for a row whose own position every renaming leaves alone,
     which is checked here: the run stops rather than fold a row that is not
     symmetric. *)
  (match Sys.getenv_opt "ROWFOLD" with
   | Some v when v <> "" ->
     for s = 0 to nsym - 1 do
       let c = conj syms.(s) rep in
       if not (same c.cp rep.cp 8 && same c.co rep.co 8
               && same c.ep rep.ep 12 && same c.eo rep.eo 12) then begin
         prerr_endline "a renaming moves this row: it cannot be folded";
         exit 1 end
     done;
     usefold := true
   | _ -> ());
  Printf.printf "the map is %.2f GB%s\n%!" (mapgb ())
    (if !usefold then Printf.sprintf ", %d pages of %d kept" nrep npage
     else "");
  if rowplace = None && not rowsolve then alloc ();

  let maxd = 32 in
  let cps = Array.init maxd (fun _ -> Array.make 8 0) in
  let eps = Array.init maxd (fun _ -> Array.make 12 0) in
  let tw = Array.make maxd 0 in
  let fl = Array.make maxd 0 in
  let sl = Array.make maxd 0 in
  let nodes = ref 0L and probes = ref 0L in
  let ish = Array.make 18 false in
  Array.iter (fun m -> ish.(m) <- true) hmoves;

  let heur d =
    Char.code (Bigarray.Array1.unsafe_get p_all
                 ((tw.(d) * n_flip + fl.(d)) * n_slice + sl.(d))) in

  (* A word of the mask table: the distance, then the moves that drop it by
     one, then the moves that do not raise it.  A move changes the distance
     by at most one, so a node with s moves to spare beyond its distance may
     take: any move if s is two or more, a move that does not raise if s is
     one, and only a move that drops if s is nought. *)
  let allmv = (1 lsl 18) - 1 in
  let mdist w = w land 31 in
  let mmask w s =
    if s >= 2 then allmv
    else if s = 1 then (w lsr 23) land allmv
    else (w lsr 5) land allmv in

  let step d m =
    let d' = d + 1 in
    let mcp = moves.(m).cp and mep = moves.(m).ep in
    for i = 0 to 7 do cps.(d').(i) <- cps.(d).(mcp.(i)) done;
    for i = 0 to 11 do eps.(d').(i) <- eps.(d).(mep.(i)) done;
    tw.(d') <- mt_twist.(tw.(d)).(m);
    fl.(d') <- mt_flip.(fl.(d)).(m);
    sl.(d') <- mt_slice.(sl.(d)).(m) in

  let mark d = mark_at cps.(d) eps.(d) in

  (* ROW_NOPREPASS=1 turns the prepass and both cuts off, which is the plain
     search: every canonical word that reaches H, counted.  That is the only
     way to compare with hcoset's published 16 019 916 192 at depth 12. *)
  (* An exported make variable that was never given a value arrives as the
     EMPTY STRING, not as nothing, so every one of these has to survive it. *)
  let getenvi name dflt =
    match Sys.getenv_opt name with
    | Some v when v <> "" -> (try int_of_string v with _ -> dflt)
    | _ -> dflt in
  let nopre = match Sys.getenv_opt "ROW_NOPREPASS" with
    | Some v -> v <> "" | None -> false in
  let cut = ref true in
  let rcut = 5 in
  (* hcoset's `enoughbits': the last search level need not be run out, only
     run until the map holds enough for the prepasses above it to finish the
     row.  Its own rule at depth 16 is 167 million plus a third of what the
     prepass left, and ROWENOUGH takes that number.  Safe like every other
     cut here -- what is proved is that the map filled. *)
  let enough = ref max_int in
  let rowenough = getenvi "ROWENOUGH" 0 in
  let opp f = (f + 3) mod 6 in
  let idx d = (tw.(d) * n_flip + fl.(d)) * n_slice + sl.(d) in

  (* The same search over the mask table.  A node is handed the moves worth
     trying, so it never builds a position the table has already ruled out --
     the eighteen tries and eighteen table reads a node become three or four
     of each. *)
  let rec dfsm d togo prev mask =
    nodes := Int64.add !nodes 1L;
    if !nset >= !enough then ()
    else if togo = 0 then begin
      probes := Int64.add !probes 1L;
      mark d
    end else begin
      let togo' = togo - 1 in
      for m = 0 to 17 do
        if mask land (1 lsl m) <> 0 then begin
          let f = m / 3 in
          if (togo > 1 || not !cut || not ish.(m))
             && (prev < 0 || not (f = prev || (f = opp prev && f > prev)))
          then begin
            step d m;
            let w = Bigarray.Array1.unsafe_get p_msk (idx (d + 1)) in
            let nd = mdist w in
            if nd <= togo'
               && (not !cut || togo' = nd || togo' + nd >= rcut) then
              dfsm (d + 1) togo' f (mmask w (togo' - nd))
          end
        end
      done
    end in

  (* When the prepass has run, the search looks only for words whose last
     move is not in H: every word that ends in H is a shorter one of the same
     row followed by moves of H, and the prepass has already played those.

     It also refuses, near the bottom, any move that does not go straight at
     H -- that is hcoset's rule, and it is empirical, not proved.  A word
     that wastes a move down there ends in moves of H, so the prepass catches
     it anyway.  Both cuts are off on a level with no prepass. *)
  let rec dfs d togo prev =
    nodes := Int64.add !nodes 1L;
    let nd = heur d in
    if nd <= togo
       && (not !cut || d = 0 || togo = nd || togo + nd >= rcut) then begin
      if togo = 0 then begin
        probes := Int64.add !probes 1L;
        mark d
      end else
        for m = 0 to 17 do
          let f = m / 3 in
          if (togo > 1 || not !cut || not ish.(m))
             && (prev < 0 || not (f = prev || (f = opp prev && f > prev)))
          then begin step d m; dfs (d + 1) (togo - 1) f end
        done
    end in

  for i = 0 to 7 do cps.(0).(i) <- rep.cp.(i) done;
  for i = 0 to 11 do eps.(0).(i) <- rep.ep.(i) done;
  tw.(0) <- twist rep; fl.(0) <- flip rep; sl.(0) <- slice rep;

  Printf.printf "row \"%s\", %d members, table cap %d, first depth %d\n%!"
    arg rowsize cap (heur 0);
  let t0 = Unix.gettimeofday () in
  let done_ = ref 0 in
  let d = ref (heur 0) in
  let d0 = heur 0 in
  while rowplace = None && not rowsolve && !done_ < rowsize
        && !d <= maxdepth do
    let before = !done_ in
    (* The prepass costs the same sweep whether the map is full or empty, so
       below some count searching is the cheaper way to the same members.
       hcoset puts it at six million and so do we.  Note what the two sides
       are: with the prepass ON the search is cut and the prepass makes up
       the difference; with it OFF the search is not cut, and an uncut level
       finds every word of that length, including the ones ending in H.  So
       either way the level is complete -- the threshold buys speed, and a
       LOWER one would buy speed at the price of completeness, which is the
       wrong trade when a row is finishing short. *)
    cut := not nopre && !d > d0 && (!done_ > 6000000 || !d > maxsearch);
    let t1 = Unix.gettimeofday () in
    if !cut then carry () else blitmaps ();
    let t2 = Unix.gettimeofday () in
    nodes := 0L; probes := 0L;
    (* the threshold is on the whole map, so what the prepass left has to be
       counted before the search starts; that costs a couple of seconds and
       only on the level the threshold applies to *)
    enough := max_int;
    if rowenough > 0 && !d = maxsearch then begin
      swapmaps (); nset := count (); swapmaps ();
      enough := rowenough
    end;
    if !d <= maxsearch then begin
      if has_mask then begin
        let w = Bigarray.Array1.unsafe_get p_msk (idx 0) in
        let nd = mdist w in
        if nd <= !d then dfsm 0 !d (-1) (mmask w (!d - nd))
      end else dfs 0 !d (-1)
    end;
    let t3 = Unix.gettimeofday () in
    swapmaps ();
    done_ := count ();
    Printf.printf
      "depth %2d : %Ld nodes, %Ld solutions, %d new, %d done, \
       prepass %.1f s, search %.1f s%s\n%!"
      !d !nodes !probes (!done_ - before) !done_ (t2 -. t1) (t3 -. t2)
      (if !enough < max_int && !nset >= !enough then " (stopped early)"
       else "");
    incr d
  done;
  Printf.printf "row \"%s\": %d of %d after depth %d, %.1f s\n%!"
    arg !done_ rowsize (!d - 1) (Unix.gettimeofday () -. t0);

  (* ---- what is left over ------------------------------------------------ *)
  (* A row that stops short leaves a few members unmarked, and each of those
     is settled on its own by a WORD: play it and the position is solved.
     hcoset does the same and hands them to Kociemba's two phase algorithm.
     Nothing here has to be trusted -- the word is checked by playing it. *)
  (* ROWLEFT is how many to settle, not a flag: these are the deepest members
     of the row, so phase one gets them into H with about ten moves to spare
     and a member of H often needs more than that.  Most phase one solutions
     therefore lead nowhere and the solver works through many of them.  A
     sample is what tells us the shape; ROWLEFT=0 means all of them. *)
  let rowleft = getenvi "ROWLEFT" (-1) in
  if (rowplace <> None || rowsolve || rowleft >= 0)
     && !done_ < rowsize then begin
    let irep = inv rep in
    let mx = 22 in
    let cps = Array.init mx (fun _ -> Array.make 8 0) in
    let eps = Array.init mx (fun _ -> Array.make 12 0) in
    let tws = Array.make mx 0 and fls = Array.make mx 0
    and sls = Array.make mx 0 in
    let path = Array.make mx 0 in
    let ix d = (tws.(d) * n_flip + fls.(d)) * n_slice + sls.(d) in
    let step1 d m =
      let d' = d + 1 in
      let mcp = moves.(m).cp and mep = moves.(m).ep in
      for i = 0 to 7 do cps.(d').(i) <- cps.(d).(mcp.(i)) done;
      for i = 0 to 11 do eps.(d').(i) <- eps.(d).(mep.(i)) done;
      tws.(d') <- mt_twist.(tws.(d)).(m);
      fls.(d') <- mt_flip.(fls.(d)).(m);
      sls.(d') <- mt_slice.(sls.(d)).(m) in
    let out = ref None in
    (* A LEFTOVER IS A DEEP POSITION, so phase one reaches H with little to
       spare and most phase one solutions lead to an element of H that cannot
       be finished inside what is left.  The solver then works through
       millions of them.  So it gives up on a length after this many and goes
       to the next, and if the position itself will not go it is tried
       inverted, which is a different tree -- that is the cheap end of what
       Rokicki does on six axes. *)
    let p1cap = getenvi "ROWP1CAP" 200000 in
    let tried = ref 0 in
    (* phase one takes it into H, phase two the rest of the way *)
    let rec p1 d togo prev mask =
      if togo = 0 then begin
        if !tried >= p1cap then true          (* give up on this length *)
        else begin
          incr tried;
          let hq = { cp = cps.(d); co = Array.make 8 0;
                     ep = eps.(d); eo = Array.make 12 0 } in
          match phase2 (h2coord hq) (20 - d) with
          | Some w2 ->
            out := Some (Array.to_list (Array.sub path 0 d) @ w2); true
          | None -> false
        end
      end else begin
        let togo' = togo - 1 in
        let r = ref false and m = ref 0 in
        while not !r && !m < 18 do
          if mask land (1 lsl !m) <> 0 then begin
            let f = !m / 3 in
            if prev < 0 || not (f = prev || (f = opp prev && f > prev))
            then begin
              step1 d !m; path.(d) <- !m;
              let w = Bigarray.Array1.unsafe_get p_msk (ix (d + 1)) in
              let nd = mdist w in
              if nd <= togo' && p1 (d + 1) togo' f (mmask w (togo' - nd))
              then r := true
            end
          end;
          incr m
        done; !r
      end in
    (* one length, one position: every phase one solution of that length is
       tried, and each is finished inside what is left, until the budget for
       the length runs out *)
    let solve1 q l =
      Array.blit q.cp 0 cps.(0) 0 8;
      Array.blit q.ep 0 eps.(0) 0 12;
      tws.(0) <- twist q; fls.(0) <- flip q; sls.(0) <- slice q;
      out := None;
      let w0 = Bigarray.Array1.unsafe_get p_msk (ix 0) in
      let nd0 = mdist w0 in
      if nd0 <= l then begin
        tried := 0;
        ignore (p1 0 l (-1) (mmask w0 (l - nd0)))
      end;
      !out in
    (* a move undone, and a word undone: play it backwards, each move the
       other way *)
    let invmv m = 3 * (m / 3) + (2 - m mod 3) in
    (* the phase one distance of a position *)
    let d1 c = mdist (Bigarray.Array1.unsafe_get p_msk
        ((twist c * n_flip + flip c) * n_slice + slice c)) in
    (* SIX AXES: the three axes of the cube, each way round.  A LENGTH IS
       TRIED ON ALL SIX BEFORE IT IS RAISED, because a shorter phase one
       leaves more room for phase two, and phase two is where these
       positions are hard.  The word comes back in the frame of the axis it
       was found on and is renamed on the way out; if the position was solved
       inverted the word is played backwards, each move the other way.

       ONE AXIS IS ALREADY EXHAUSTED for a leftover of the row: the row
       itself is a two phase search on axis nought, complete up to the depth
       the search reached.  What the other five buy is a different tree. *)
    let rowtrace = match Sys.getenv_opt "ROWTRACE" with
      | Some v -> v <> "" | None -> false in
    let solve20 q =
      let vars = Array.init 6 (fun k ->
        let a = axes.(k / 2) in
        let qa = mult (mult (inv a) q) a in
        (k / 2, k mod 2 = 1, if k mod 2 = 0 then qa else inv qa)) in
      let res = ref None and l = ref 0 in
      let t0 = Unix.gettimeofday () in
      while !res = None && !l <= 20 do
        Array.iteri (fun k (i, invd, qq) ->
          if !res = None && d1 qq <= !l then begin
            (match solve1 qq !l with
             | Some w ->
               res := Some (if invd then List.rev_map (fun m -> axmv i (invmv m)) w
                            else List.map (axmv i) w)
             | None -> ());
            if rowtrace then
              Printf.printf "      length %d, axis %d%s: %d tried, %.1f s\n%!"
                !l k (if !tried >= p1cap then " (gave up)" else "")
                !tried (Unix.gettimeofday () -. t0)
          end) vars;
        incr l
      done;
      !res in
    (* The phase one distance, on each axis and each way round.  It is the
       number that decides everything: twenty less the smallest of the six is
       all phase two has to work in, and a member of H usually wants fourteen
       to sixteen moves of H. *)
    let axd q =
      let l = ref [] in
      for i = Array.length axes - 1 downto 0 do
        let a = axes.(i) in
        let qa = mult (mult (inv a) q) a in
        l := d1 qa :: d1 (inv qa) :: !l
      done;
      !l in
    let axds q = String.concat " " (List.map string_of_int (axd q)) in
    let axdmin q = List.fold_left min 99 (axd q) in
    (* a move, written the usual way, so a witness can be read by eye        *)
    let _ = () in
    let mvname m =
      Printf.sprintf "%c%s" faces.[m / 3]
        (match m mod 3 with 0 -> "" | 1 -> "2" | _ -> "'") in
    let solves q w =
      let c = ref q in
      List.iter (fun m -> c := mult !c moves.(m)) w;
      let ok = ref true in
      for i = 0 to 7 do
        if (!c).cp.(i) <> i || (!c).co.(i) <> 0 then ok := false done;
      for i = 0 to 11 do
        if (!c).ep.(i) <> i || (!c).eo.(i) <> 0 then ok := false done;
      !ok in
    let t1 = Unix.gettimeofday () in
    let seen = ref 0 and bad = ref 0 and worst = ref 0 and hist = Array.make 25 0 in
    (* ROWSOLVE="<moves>" solves the position that scramble gives, which is
       the check on the solver itself: an ordinary position must go. *)
    (match Sys.getenv_opt "ROWSOLVE" with
     | Some v when v <> "" ->
       let q = ref (solved ()) in
       List.iter (fun m -> q := mult !q moves.(m)) (parse_moves v);
       let q = !q in
       Printf.printf "scramble : phase one, six axes, %s\n%!" (axds q);
       (match solve20 q with
        | Some w when solves q w ->
          Printf.printf "%d moves : %s\n"
            (List.length w) (String.concat " " (List.map mvname w))
        | Some _ -> print_string "a word that does not solve it\n"
        | None -> print_string "no word of twenty\n");
       exit 0
     | _ -> ());
    (* one place on its own, and then nothing else                          *)
    (match rowplace with
     | Some (pg, g, b) ->
       let q = mult irep (unplace pg g b) in
       Printf.printf "place %d %d %d : phase one, six axes, %s\n%!"
         pg g b (axds q);
       (match solve20 q with
        | Some w when solves q w ->
          Printf.printf "%d moves : %s\n"
            (List.length w) (String.concat " " (List.map mvname w))
        | Some _ -> print_string "a word that does not solve it\n"
        | None -> print_string "no word of twenty\n");
       exit 0
     | None -> ());
    Printf.printf "the leftovers, one word each%s\n%!"
      (if rowleft = 0 then "" else Printf.sprintf " (the first %d)" rowleft);
    let clo = if !usefold then !fculo else !culo
    and chi = if !usefold then !fcuhi else !cuhi in
    (try
    for pgi = 0 to (if !usefold then nrep else npage) - 1 do
      let pg = if !usefold then reps.(pgi) else pgi in
      for g = 0 to ngroup - 1 do
        let i = pgi * ngroup + g in
        let lo = Bigarray.Array1.unsafe_get clo i
        and hi = Bigarray.Array1.unsafe_get chi i in
        if lo <> 4095 || hi <> 4095 then
          for b = 0 to 23 do
            let set = if b < 12 then lo land (1 lsl b) <> 0
                      else hi land (1 lsl (b - 12)) <> 0 in
            if not set then begin
              incr seen;
              let q = mult irep (unplace pg g b) in
              (match solve20 q with
               | Some w when List.length w <= 20 && solves q w ->
                 let n = List.length w in
                 hist.(n) <- hist.(n) + 1;
                 if n > !worst then worst := n;
                 (* the witness itself: the place, then the word, as move
                    numbers for a machine and as moves for a reader *)
                 Printf.printf "LEFT %d %d %d %d%s   # %s\n"
                   pg g b n
                   (String.concat ""
                      (List.map (fun m -> " " ^ string_of_int m) w))
                   (String.concat " " (List.map mvname w))
               | _ ->
                 incr bad;
                 (* say WHY: the phase one distance is what phase two is left
                    to work in, and an element of H usually wants fourteen to
                    sixteen moves of H *)
                 Printf.printf
                   "LEFT %d %d %d NONE   # phase one, six axes, %s, \
                    leaves %d for phase two\n" pg g b (axds q)
                   (20 - axdmin q));
              Printf.printf "   %d done, %d without a word, %.1f s\n%!"
                !seen !bad (Unix.gettimeofday () -. t1);
              if rowleft > 0 && !seen >= rowleft then raise Exit
            end
          done
      done
    done
    with Exit -> ());
    Printf.printf "%d settled, %d without a word of 20, longest %d, %.1f s\n%!"
      !seen !bad !worst (Unix.gettimeofday () -. t1);
    for n = 0 to 24 do
      if hist.(n) > 0 then Printf.printf "   %2d moves : %d\n" n hist.(n) done
  end
