#!/bin/sh
# generates Fs_00.v .. Fs_15.v, one slice of checkStep each
for n in 00 01 02 03 04 05 06 07 08 09 10 11 12 13 14 15; do
  d=$(expr $n + 0)
  cat > Fs_$n.v <<EOF
(* =========================================================================  *)
(*  Fs_$n.v -- GENERATED by mkfs.sh, do not edit                               *)
(*                                                                            *)
(*  Slice $d of sixteen of checkStep: the 1 048 576 coordinates starting at    *)
(*  cstart $d.  About four and a half minutes.  Fsmain.v glues the sixteen.    *)
(* =========================================================================  *)

From mathcomp Require Import all_ssreflect all_fingroup.
From Stdlib Require Import Uint63.
From Stdlib Require Import -(notations) PArray.
From Rubik Require Import ssrint63.
From Rubik Require Import Cyc Ball Table Search Tsearch Tabi Rubik333 Sym Root.
From Rubik Require Import Coord Coordfs Coordfsi Fstab FsTable Diameter Moves.
From Rubik Require Import Fspar.

Lemma fschk_$n : all_pow cbits (cstart $d) chunkF.
Proof. Time native_cast_no_check (erefl true). Qed.
EOF
done
