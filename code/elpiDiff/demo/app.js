// app.js: the page. Loads tree-sitter-julia and Elpi (wasm), compiles the
// Elpi sources of elpiDiff once, then runs pipeline.js on each click.
import { Parser, Language } from './vendor/web-tree-sitter.js';
import { loadElpi, run, argumentsOf } from './pipeline.js';
import { EXAMPLES } from './examples.js';

const $ = id => document.getElementById(id);
const t0 = 0;                                   // times from the start of navigation
const status = (text, busy = false) => { $('status').textContent = text; $('status').classList.toggle('busy', busy); };
const sec = ms => (ms / 1000).toFixed(1) + ' s';
const urlOf = f => new URL(f, document.baseURI).href;

// examples menu
for (const [i, e] of EXAMPLES.entries()) $('example').add(new Option(e.name, String(i)));
$('src').value = EXAMPLES[0].code;

async function startParser() {
  await Parser.init({ locateFile: f => urlOf('vendor/' + f) });
  const parser = new Parser();
  parser.setLanguage(await Language.load(urlOf('vendor/tree-sitter-julia.wasm')));
  return parser;
}

async function startElpi() {
  while (!globalThis.elpi) await new Promise(r => setTimeout(r, 10));
  const tWasm = performance.now() - t0;
  status('Compiling the Elpi sources of elpiDiff…', true);
  await new Promise(r => setTimeout(r, 0));               // let the status paint
  const get = f => fetch(urlOf('elpi/' + f)).then(r => {
    if (!r.ok) throw new Error(`cannot load elpi/${f} (${r.status})`);
    return r.text();
  });
  const t = performance.now();
  const base = await loadElpi(globalThis.elpi, get);
  return { E: globalThis.elpi, base: base.id, tWasm, tCompile: performance.now() - t };
}

const state = {};
const ready = (async () => {
  const [parser, elpi] = await Promise.all([startParser(), startElpi()]);
  Object.assign(state, { parser, ...elpi });
  buildArgs();
  state.loadMs = performance.now() - t0;
  $('go').disabled = false;
  status(`Ready (loaded in ${sec(state.loadMs)}). Ctrl+Enter differentiates.`);
})().catch(e => { status('Loading failed: ' + e.message); throw e; });

// The arguments of each function, with a checkbox: checked = differentiated.
// choices remembers the boxes by function and argument name, so that an edit
// keeps the choice of the arguments whose names did not change.
const choices = new Map();
const key = (f, x) => f + '\u0000' + x;

function buildArgs() {
  if (!state.parser) return;
  const fns = argumentsOf(state.parser, $('src').value);
  if (fns === null) return;                        // does not parse: keep the last list
  const box = $('args-list');
  box.replaceChildren();
  show('args', fns.length > 0);
  for (const { fn, args } of fns) {
    const row = document.createElement('div');
    row.className = 'fn-args';
    const name = document.createElement('code');
    name.textContent = fn;
    row.append(name);
    if (args.length === 0) row.append(Object.assign(document.createElement('span'), { className: 'why', textContent: 'no arguments' }));
    for (const a of args) {
      const l = document.createElement('label');
      const c = document.createElement('input');
      c.type = 'checkbox';
      c.dataset.fn = fn; c.dataset.arg = a.name;
      if (a.choosable) {
        c.checked = choices.has(key(fn, a.name)) ? choices.get(key(fn, a.name)) : true;
        c.addEventListener('change', () => choices.set(key(fn, a.name), c.checked));
      } else {
        c.checked = false; c.disabled = true; l.classList.add('off'); l.title = a.reason;
      }
      const n = document.createElement('code'); n.textContent = a.name;
      l.append(c, n);
      if (!a.choosable) l.append(Object.assign(document.createElement('span'), { className: 'why', textContent: a.reason }));
      row.append(l);
    }
    box.append(row);
  }
}

// the arguments made passive: the unchecked boxes that can be checked
const passiveChoice = () => [...document.querySelectorAll('#args-list input:not(:disabled)')]
  .filter(c => !c.checked).map(c => [c.dataset.fn, c.dataset.arg]);

let editTimer = null;
$('src').addEventListener('input', () => { clearTimeout(editTimer); editTimer = setTimeout(buildArgs, 300); });

function show(id, on) { $(id).classList.toggle('hidden', !on); }

function message(cls, title, lines) {
  const d = document.createElement('div');
  d.className = 'msg ' + cls;
  const b = document.createElement('b'); b.textContent = title; d.append(b);
  for (const l of lines) { d.append(document.createElement('br'), document.createTextNode(l)); }
  $('messages').append(d);
}

// the first line of a generated file names its source: say where it comes from
const retitle = code => code.replace(/^# Generated by adjudge from .*$/m,
  '# Generated by elpiDiff (adjudge) in the browser. Do not edit.');

function differentiate() {
  const modes = ['tangent', 'adjoint'].filter(m => $('m-' + m).checked);
  $('messages').replaceChildren();
  for (const m of ['tangent', 'adjoint']) show('out-' + m, false);
  show('l0-box', false); show('facts-box', false); show('placeholder', false); show('out-title', true);
  if (modes.length === 0) { message('note', 'Choose tangent, adjoint or both.', []); return null; }
  const t = performance.now();
  let r;
  clearTimeout(editTimer); buildArgs();
  try { r = run(state.E, state.base, state.parser, $('src').value, modes, 'editor', passiveChoice()); }
  catch (e) { message('bad', 'Internal error', [String(e.message || e)]); status('Failed.'); return null; }
  const ms = performance.now() - t;
  if (r.facts) { $('facts').textContent = r.facts; show('facts-box', true); }
  if (r.stage === 'syntax') message('bad', 'The Julia code does not parse', [r.message]);
  else if (r.stage === 'front') message('bad', 'Refused by the Julia front end', [r.message]);
  else {
    $('l0').textContent = r.l0; show('l0-box', true);
    for (const m of modes) {
      const o = r.modes[m];
      if (o.error) { message('bad', `${m}: the tool failed`, [o.error]); continue; }
      if (o.refused.length) message('bad', `${m}: refused by the tool`, o.refused);
      if (o.code) { $('code-' + m).textContent = retitle(o.code); show('out-' + m, true); }
      else if (!o.refused.length) message('note', `${m}: no function to differentiate`, []);
    }
  }
  const detail = Object.entries(r.ms).map(([k, v]) => `${k} ${v.toFixed(0)}`).join(', ');
  status(`Done in ${ms.toFixed(0)} ms.`);
  $('timing').textContent = `Last run: ${ms.toFixed(0)} ms (${detail} ms). Page load: ${sec(state.loadMs)} ` +
    `(Elpi wasm ${sec(state.tWasm)}, compiling elpiDiff ${sec(state.tCompile)}).`;
  return { ...r, totalMs: ms };
}

function go() {
  if ($('go').disabled) return;
  $('go').disabled = true;
  status('Differentiating…', true);
  setTimeout(() => { try { differentiate(); } finally { $('go').disabled = false; } }, 0);
}

$('go').addEventListener('click', go);
$('example').addEventListener('change', () => {
  $('src').value = EXAMPLES[Number($('example').value)].code;
  buildArgs();
  if (!$('go').disabled) go();
});
$('src').addEventListener('keydown', e => {
  if (e.key === 'Enter' && (e.ctrlKey || e.metaKey)) { e.preventDefault(); go(); }
});
for (const b of document.querySelectorAll('[data-copy]'))
  b.addEventListener('click', async () => {
    try { await navigator.clipboard.writeText($(b.dataset.copy).textContent); b.textContent = 'Copied'; }
    catch { b.textContent = 'Select and copy'; }
    setTimeout(() => { b.textContent = 'Copy'; }, 1500);
  });

// for the headless test (test/cdp.js)
window.demo = { ready, state, differentiate, buildArgs, passiveChoice };
ready.then(() => go());
